import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
const browser=await chromium.launch({headless:true});
try{
 const page=await browser.newPage({viewport:{width:1440,height:900}}),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto(process.env.ROVER_TEST_URL||'http://localhost:8765');
 await page.getByRole('button',{name:'Replay',exact:true}).click();
 await page.waitForFunction(()=>document.querySelector('video')?.readyState>=2);
 await page.getByRole('button',{name:'Play replay',exact:true}).first().click();
 await page.waitForFunction(()=>document.querySelector('video').currentTime>.5);
 await page.waitForSelector('.video-surface[data-ready=true]');
 assert.ok(await page.getByLabel('Recording time').count());
 console.log('Video playback and capture clock passed');
 await page.getByRole('button',{name:'Pause replay',exact:true}).click();
 await page.getByRole('slider',{name:'Full recording timeline'}).evaluate(el=>{Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(el,'330');el.dispatchEvent(new Event('input',{bubbles:true}));el.dispatchEvent(new Event('change',{bubbles:true}));});
 await page.waitForFunction(()=>Math.abs(document.querySelector('video').currentTime-30)<1);
 console.log('Cross-file seeking passed');
 await page.getByRole('button',{name:'Playback speed',exact:true}).click();
 await page.getByRole('button',{name:'Custom',exact:true}).click();
 await page.getByRole('spinbutton',{name:'Custom playback speed'}).fill('37');
 await page.getByRole('button',{name:'Apply speed'}).click();
 await page.getByRole('button',{name:'Play replay',exact:true}).first().click();
 await page.waitForFunction(()=>Number(document.querySelector('.timeline').value)>335);
 await page.getByRole('button',{name:'Pause replay',exact:true}).click();
 await page.getByRole('slider',{name:'Full recording timeline'}).evaluate(el=>{Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(el,'298');el.dispatchEvent(new Event('input',{bubbles:true}));el.dispatchEvent(new Event('change',{bubbles:true}));});
 await page.getByRole('button',{name:'Play replay',exact:true}).first().click();
 await page.waitForFunction(()=>Number(document.querySelector('.timeline').value)>305);
 await page.getByRole('button',{name:'Pause replay',exact:true}).click();
 assert.equal(await page.locator('video').count(),1);
 assert.equal(await page.getByRole('slider',{name:'Full recording timeline'}).count(),1);
 assert.ok(!/segments|timelapse/i.test(await page.locator('body').innerText()));
 const alpha=await page.locator('.video-surface').evaluate(canvas=>canvas.getContext('2d').getImageData(10,10,1,1).data[3]);
 assert.equal(alpha,255,'decoded frame remains visible across boundary');
 console.log('Continuous playback and retained frame across recording boundary passed');
 await page.screenshot({path:join(tmpdir(),'team18-replay.png')});
 assert.equal(errors.length,0,errors.join('\n'));
 await page.getByRole('button',{name:'Live',exact:true}).click();
 await page.getByRole('img',{name:'Live rover camera'}).waitFor();
 await page.getByLabel('Current time').waitFor();
 await page.setViewportSize({width:390,height:844});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'mobile layout must not overflow');
 console.log('Custom 37x speed and return to live passed; no JavaScript errors.');
}finally{await browser.close();}
